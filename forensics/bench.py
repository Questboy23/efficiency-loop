#!/usr/bin/env python3
"""Measure forensics false-positive and detection rates; write forensics/RESULTS.md.

Run: python3 forensics/bench.py   (read-only on ~/ data; nothing leaves the machine)
"""
import glob
import hashlib
import math
import os
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from forensics import check, gen  # noqa: E402

N_SEEDS = 20
H = os.path.expanduser("~")


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0, c - h), min(1, c + h))


def fmt(k, n):
    lo, hi = wilson(k, n)
    return "%d/%d = %.1f%% (95%% CI %.1f-%.1f%%)" % (k, n, 100.0 * k / max(n, 1), 100 * lo, 100 * hi)


def run_text(name, text):
    p = os.path.join(tempfile.mkdtemp(), name)
    with open(p, "w") as f:
        f.write(text)
    return check.analyze(p)


def real_files():
    pats = [H + "/hospitalprice/out/tables/*.csv", H + "/*/reports/*.csv", H + "/*/results/*.csv",
            H + "/*/data/*.csv", H + "/*/*.csv", H + "/*/*/*.csv", H + "/*/*/*/*.csv"]
    seen, out = set(), []
    for pat in pats:
        for f in sorted(glob.glob(pat)):
            if any(x in f for x in ("node_modules", "/Library/", "efficiency-loop", ".venv", "site-packages")):
                continue
            try:
                h = hashlib.md5(open(f, "rb").read()).hexdigest()
            except OSError:
                continue
            if h in seen:
                continue
            seen.add(h)
            out.append(f)
    return out


def main():
    lines = ["# Forensics results", "",
             "Generated by `python3 forensics/bench.py` on %s. Every number below comes from that script." % time.strftime("%Y-%m-%d %H:%M"), ""]
    # 1 synthetic real-shaped
    lines += ["## False positives on synthetic real-shaped data", "", "| shape | trips |", "|---|---|"]
    tot_k = tot_n = 0
    for fn in gen.REAL_SHAPED:
        ext = "md" if fn is gen.stats_table_md else "csv"
        k = sum(run_text("x." + ext, fn(s))["tripped"] for s in range(100, 100 + 5 * N_SEEDS))
        lines.append("| %s | %s |" % (fn.__name__, fmt(k, 5 * N_SEEDS)))
        tot_k += k
        tot_n += 5 * N_SEEDS
    lines.append("| all | %s |" % fmt(tot_k, tot_n))
    # 2 real files on disk
    files = real_files()
    rows, k, n = [], 0, 0
    for f in files:
        try:
            r = check.analyze(f)
        except Exception as e:  # report, never hide
            rows.append((f, "ERROR %s" % e))
            continue
        if r["n_numbers"] < check.MIN_NUMBERS:
            continue
        n += 1
        if r["tripped"]:
            k += 1
            rows.append((f, ", ".join("%s[%s]" % (x["test"], x["col"]) for x in r["findings"][:3])))
    lines += ["", "## False positives on real files on this machine (read-only, byte-identical copies counted once)", "",
              "Files with at least 50 numbers: %d. Tripped: %s." % (n, fmt(k, n)), "",
              "Files that tripped:", ""]
    lines += ["- `%s`: %s" % (f.replace(H, "~"), why[:160]) for f, why in rows]
    lines += ["", "Caveat: thresholds were adjusted over three rounds while looking at these files (first on half of the hospital/reports/results files, "
              "then on the rest, then on the data/ folders), so this is a tuned rate, not a held-out rate. "
              "A fresh held-out rate needs files the checker has never been developed against."]
    # 3 detection
    lines += ["", "## Detection of fabricated-shaped data (%d seeds per shape)" % N_SEEDS, "",
              "| shape | detected | caught by expected test |", "|---|---|---|"]
    dk = dn = ek = 0
    for fab in gen.FABRICATED:
        det = exp = 0
        for s in range(200, 200 + N_SEEDS):
            name, text, expected = fab(s)
            r = run_text(name, text)
            det += r["tripped"]
            hit = [x["test"] for x in r["findings"]]
            exp += any(e in h for h in hit for e in expected)
        lines.append("| %s | %s | %d/%d |" % (name, fmt(det, N_SEEDS), exp, N_SEEDS))
        dk += det
        dn += N_SEEDS
        ek += exp
    lines.append("| all | %s | %d/%d |" % (fmt(dk, dn), ek, dn))
    lines += ["", "Caveat: the fabricated shapes were written by the same author as the checker, so this is a unit-level detection rate, not evidence about LLM-written fakes."]
    # 4 runtime
    big = os.path.join(tempfile.mkdtemp(), "big.csv")
    open(big, "w").write(gen.lognormal_csv(1, n=150000) * 1)
    ts = []
    for _ in range(5):
        a = time.perf_counter()
        subprocess.run([sys.executable, os.path.join(ROOT, "forensics", "check.py"), big])
        ts.append(time.perf_counter() - a)
    lines += ["", "## Runtime", "", "`check.py` on a %.1f MB CSV, whole process including interpreter start: median %.0f ms, max %.0f ms (5 runs)."
              % (os.path.getsize(big) / 1e6, 1000 * sorted(ts)[2], 1000 * max(ts))]
    with open(os.path.join(ROOT, "forensics", "RESULTS.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
